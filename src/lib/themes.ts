// Theme and accent definitions. Kept free of imports so scripts/check-contrast.ts
// can load this file directly with Node and measure the real contrast ratios.

export interface ThemeTokens {
  background: string;
  surface: string;
  surfaceMuted: string;
  text: string;
  textMuted: string;
  primary: string;
  onPrimary: string;
  primarySoft: string;
  secondary: string;
  border: string;
  // Used where a boundary identifies a control (inputs, checkboxes); needs 3:1.
  borderStrong: string;
  focus: string;
  danger: string;
  // Decorative cube colors for brand and inventory icons. Never used for text.
  cubeA: string;
  cubeB: string;
  cubeC: string;
  // How strongly block headers take on their cube color: "0%" keeps them plain.
  // Unlike the other tokens this is a percentage, not a color.
  blockTint: string;
}

